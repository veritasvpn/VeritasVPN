#!/usr/bin/env python3
"""Generates en and es-419 Localizable.strings for the Apple clients.

Keys are the English UI sentences themselves (see Platform/Localization.swift).
The script scans the app sources and the user-facing VeritasCore files for
string literals that look like UI text, and takes Spanish (Latin America)
translations from Scripts/es-419.json.

  python3 Scripts/l10n.py          # write the .strings files
  python3 Scripts/l10n.py --check  # CI: fail on missing translations or stale files
"""
import json
import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
SOURCES = [ROOT / "VeritasVPN"]
CORE = ROOT / "Packages/VeritasCore/Sources/VeritasCore"
CORE_FILES = [CORE / "Messages.swift", CORE / "Shield.swift", CORE / "HeroLogic.swift", CORE / "Plans.swift"]
TRANSLATIONS = ROOT / "Scripts/es-419.json"
OUT = ROOT / "VeritasVPN/Resources"

LITERAL = re.compile(r'"((?:[^"\\\n]|\\.)*)"')
TRIPLE = re.compile(r'""".*?"""', re.S)
LINE_COMMENT = re.compile(r'//[^\n]*')


def unescape(text):
    return (text.replace('\\"', '"').replace("\\n", "\n").replace("\\t", "\t").replace("\\\\", "\\"))


def looks_like_ui(text):
    if not re.search(r"[A-Za-z]", text) or "\\(" in text:
        return False
    if text.startswith(("http", "mailto", "veritas.", "cloud.", "group.", "Inter-", "SpaceGrotesk-", "$(")):
        return False
    if " " in text or "\n" in text:
        return True
    if text.endswith("…"):
        return True
    # Single words: Capitalized ("Account") or ALL CAPS ("HELP").
    return bool(re.fullmatch(r"[A-Z][a-z’']+[.?!]?|[A-Z]{2,}", text))


def strip_comments(source):
    out = []
    for line in source.splitlines():
        # Drop // comments that are not inside a literal (good enough here).
        if "//" in line and line.count('"') == 0:
            line = LINE_COMMENT.sub("", line)
        elif line.lstrip().startswith("//"):
            line = ""
        out.append(line)
    return "\n".join(out)


def collect(ignore):
    files = [p for d in SOURCES for p in sorted(d.rglob("*.swift"))] + CORE_FILES
    keys = {}
    for path in files:
        text = strip_comments(TRIPLE.sub("", path.read_text(encoding="utf-8")))
        for match in LITERAL.finditer(text):
            key = unescape(match.group(1))
            if looks_like_ui(key) and key not in ignore:
                keys.setdefault(key, path.relative_to(ROOT).as_posix())
    return dict(sorted(keys.items()))


def escape(text):
    return text.replace("\\", "\\\\").replace('"', '\\"').replace("\n", "\\n")


def render(pairs):
    lines = ["/* Generated by Scripts/l10n.py. Edit Scripts/es-419.json, not this file. */", ""]
    for key, value in pairs:
        lines.append(f'"{escape(key)}" = "{escape(value)}";')
    return "\n".join(lines) + "\n"


def main():
    check = "--check" in sys.argv
    data = json.loads(TRANSLATIONS.read_text(encoding="utf-8"))
    ignore = set(data.get("_ignore", []))
    spanish = data.get("strings", {})
    keys = collect(ignore)

    missing = [k for k in keys if k not in spanish]
    unused = [k for k in spanish if k not in keys]
    bad_format = [k for k in keys if k in spanish and re.findall(r"%[@dl]+|%lld|%llu", k) != re.findall(r"%[@dl]+|%lld|%llu", spanish[k])]

    outputs = {
        OUT / "en.lproj/Localizable.strings": render((k, k) for k in keys),
        OUT / "es-419.lproj/Localizable.strings": render((k, spanish.get(k, k)) for k in keys),
    }

    problems = []
    if missing:
        problems.append("Missing es-419 translations:\n  " + "\n  ".join(f"{k!r} ({keys[k]})" for k in missing))
    if bad_format:
        problems.append("Placeholders differ between English and Spanish:\n  " + "\n  ".join(map(repr, bad_format)))
    if unused:
        print("note: unused translations:\n  " + "\n  ".join(map(repr, unused)))

    if check:
        for path, content in outputs.items():
            if not path.exists() or path.read_text(encoding="utf-8") != content:
                problems.append(f"{path.relative_to(ROOT)} is out of date. Run Scripts/l10n.py.")
        if problems:
            print("\n\n".join(problems), file=sys.stderr)
            return 1
        print(f"l10n OK: {len(keys)} strings, en + es-419")
        return 0

    for path, content in outputs.items():
        path.parent.mkdir(parents=True, exist_ok=True)
        path.write_text(content, encoding="utf-8")
    if problems:
        print("\n\n".join(problems), file=sys.stderr)
        return 1
    print(f"wrote {len(keys)} strings")
    return 0


if __name__ == "__main__":
    sys.exit(main())
